#!/usr/bin/env python3
"""Generate references/decisions.md, the one-page index of every rule.

The index lists each rule's ID and title under its document, so an agent
assessing a repository can walk the whole set without loading every
document. It is generated from the `## XX-n. Title` headings of the
convention documents; test_apply.py fails when the committed index is
stale.

Usage:  python3 build_index.py          rewrite references/decisions.md
        python3 build_index.py --check  exit 1 when the file is stale
"""

from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REFERENCES = os.path.normpath(os.path.join(HERE, "..", "references"))
INDEX = os.path.join(REFERENCES, "decisions.md")

DOCUMENTS = (
    ("layout.md", "Layout and naming"),
    ("bazel.md", "Bazel"),
    ("rust.md", "Rust"),
    ("python.md", "Python"),
    ("typescript.md", "TypeScript"),
    ("proto.md", "Protocol buffers and gRPC"),
    ("testing.md", "Testing"),
    ("gates.md", "Gates"),
    ("automation.md", "Automation"),
    ("dependencies.md", "Dependencies and version pins"),
    ("agent-setup.md", "Agent setup"),
)

RULE_RE = re.compile(r"^## ([A-Z]{2}-\d+)\. (.+)$")


def rules(path: str) -> list[tuple[str, str]]:
    found = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            match = RULE_RE.match(line.rstrip("\n"))
            if match:
                found.append((match.group(1), match.group(2)))
    return found


def slug(heading: str) -> str:
    """The anchor a Markdown renderer gives a heading: lowercase, punctuation
    dropped, spaces to hyphens, the way GitHub and most renderers do it."""
    text = heading.strip().lower()
    text = re.sub(r"[^\w\s-]", "", text)
    return re.sub(r"\s", "-", text)


def render() -> str:
    lines = [
        "# Every rule at a glance",
        "",
        "Generated by scripts/build_index.py from the rule headings; do not edit",
        "by hand. Each entry links to the rule, which carries the reason, the",
        "rejected alternatives and, where the rule is not universal, when it",
        "applies. An assessment walks this list top to bottom.",
        "",
    ]
    for document, title in DOCUMENTS:
        lines.append(f"## {title} ({document})")
        lines.append("")
        for rule_id, rule_title in rules(os.path.join(REFERENCES, document)):
            lines.append(f"- [{rule_id}]({document}#{slug(f'{rule_id}. {rule_title}')}) {rule_title}")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    content = render()
    if "--check" in argv:
        try:
            with open(INDEX, encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = ""
        if current != content:
            print("references/decisions.md is stale; run scripts/build_index.py", file=sys.stderr)
            return 1
        return 0
    with open(INDEX, "w", encoding="utf-8") as handle:
        handle.write(content)
    print(f"wrote {INDEX}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
