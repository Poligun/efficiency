# aspects and shape
# --------------------------------------------------------------------------


def compute_aspects(files: list[dict]) -> dict:
    def has(sig: str) -> list[str]:
        return [f["path"] for f in files if sig in f["signals"]]

    wire_files = [f for f in files if f["role"] == "wire_contract"]
    breaking = has("wire_breaking")
    routes = has("http_route_touched")
    clis = has("cli_surface_touched")
    build = has("build_contract_touched")
    api_files = [
        f["path"] for f in files
        if "api_surface_touched" in f["signals"] and f["role"] != "generated"
    ]
    new_source = [f["path"] for f in files if f["status"] == "A" and f["role"] == "source"]
    new_modules = has("new_module")

    code = [f for f in files if f["role"] in ("source", "wire_contract")]
    code_lines = sum((f["added"] or 0) + (f["removed"] or 0) for f in code)

    aspects = {}

    # build/codegen contracts count: a four-line change to build.rs can alter every
    # generated type in a package. Omitting it here while still listing it in
    # `files` and `why` left the aspect inactive on a pure-codegen change.
    wire_active = bool(wire_files or routes or clis or build)
    wire_why = []
    if wire_files:
        wire_why.append(f"{len(wire_files)} wire-contract file(s) changed")
    if breaking:
        wire_why.append(f"wire_breaking in {', '.join(breaking)}")
    if routes:
        wire_why.append(f"{len(routes)} file(s) with route changes")
    if clis:
        wire_why.append(f"{len(clis)} file(s) with CLI surface changes")
    if build:
        wire_why.append(f"build/codegen contract touched: {', '.join(build)}")
    aspects["wire_api"] = {
        "active": wire_active,
        "strength": "strong" if (breaking or any(f["status"] == "A" for f in wire_files)) else "weak",
        "why": "; ".join(wire_why) or "no wire contract, route, or CLI changes",
        "files": sorted({f["path"] for f in wire_files} | set(routes) | set(clis) | set(build)),
    }

    aspects["code_api"] = {
        "active": bool(api_files),
        "strength": "strong" if (len(api_files) >= 3 or new_source) else "weak",
        "why": (
            f"{len(api_files)} file(s) changed exported surface"
            + (f"; {len(new_source)} new source file(s)" if new_source else "")
        ) if api_files else "no exported surface changed",
        "files": sorted(api_files),
    }

    aspects["logic"] = {
        "active": code_lines >= 25,
        "strength": "strong" if code_lines >= 150 else "weak",
        "why": f"{code_lines} changed line(s) in source/wire files (threshold 25)",
        "files": sorted(f["path"] for f in code),
    }

    conv_files = sorted(set(new_source) | set(new_modules))
    new_dirs = {os.path.dirname(p) for p in new_source}
    existing_dirs = {os.path.dirname(f["path"]) for f in files if f["status"] != "A"}
    whole_new_dir = bool(new_dirs - existing_dirs)
    aspects["convention"] = {
        "active": bool(conv_files),
        "strength": "strong" if whole_new_dir else "weak",
        "why": (
            f"{len(new_source)} new source file(s)"
            + ("; a whole new directory appeared" if whole_new_dir else "")
        ) if conv_files else "no new code — conventions are only audited on new code",
        "files": conv_files,
    }

    return aspects


def compute_shape(code_files: int, code_lines: int) -> str:
    """Pick the cost shape from how much code actually changed.

    `focused` keys on line count alone. The shape exists to answer "does the
    whole diff fit in the orchestrator's context, such that delegating costs
    more than it saves" — and that is a question about volume, not spread.
    Requiring few files as well misclassified a 500-line single-file rewrite as
    small; requiring both (`and`) would misclassify a 40-line change spread over
    eight files as large. File count only matters for `deep`, where sharding by
    directory needs directories to shard by.
    """
    if code_lines > 2000 or code_files > 40:
        return "deep"
    if code_lines < 150:
        return "focused"
    return "standard"


# --------------------------------------------------------------------------


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--base", help="base ref (default: upstream -> origin/HEAD -> main -> master)")
    ap.add_argument("--repo", default=".", help="repo path (default: cwd)")
    ap.add_argument("--no-untracked", action="store_true", help="skip untracked files")
    ap.add_argument("--max-file-bytes", type=int, default=400_000)
    ap.add_argument("--pretty", action="store_true")
    args = ap.parse_args()

    repo = os.path.abspath(args.repo)
    try:
        git(repo, "rev-parse", "--git-dir")
    except RuntimeError:
        print(json.dumps({"error": "not a git repository", "repo": repo}), file=sys.stderr)
        return 2

    base = resolve_base(repo, args.base)
    if not base:
        print(json.dumps({"error": "no base ref resolvable"}), file=sys.stderr)
        return 3

    merge_base = git(repo, "merge-base", base, "HEAD").strip()
    head = git(repo, "rev-parse", "HEAD").strip()

    # One range covering committed AND uncommitted work: `git diff <merge-base>`
    # with no second ref compares against the working tree. That is what puts a
    # not-yet-committed debug line in scope, which is often exactly what you
    # want caught before it ships.
    numstat = parse_numstat(git(repo, "diff", "--numstat", merge_base))
    status = parse_name_status(git(repo, "diff", "--name-status", merge_base))
    patch = git(repo, "diff", "--unified=0", merge_base)
    hunks = split_patch_by_file(patch)
    # These are independent facts, not alternatives: a file can be added in a
    # commit on this branch AND further edited in the working tree. The report
    # needs both, because only committed hunks can carry inline PR comments.
    worktree_paths = set(parse_name_status(git(repo, "diff", "--name-status", "HEAD")))
    committed_paths = set(parse_name_status(git(repo, "diff", "--name-status", merge_base, "HEAD")))

    untracked: list[str] = []
    if not args.no_untracked:
        untracked = [
            p for p in git(repo, "ls-files", "--others", "--exclude-standard").splitlines() if p
        ]

    dirty = bool(worktree_paths or untracked)
    all_paths = sorted(set(numstat) | set(untracked))
    if not all_paths:
        print(json.dumps({"error": "empty range", "base": base, "merge_base": merge_base}), file=sys.stderr)
        return 4

    files: list[dict] = []
    notes: list[str] = []
    excluded: dict[str, int] = {}

    for path in all_paths:
        is_untracked = path in untracked and path not in numstat
        added, removed = numstat.get(path, (0, 0))
        is_binary = added is None
        added = added or 0
        removed = removed or 0

        full = os.path.join(repo, path)
        try:
            size = os.path.getsize(full)
        except OSError:
            size = 0
        too_big = size > args.max_file_bytes

        header = "" if (is_binary or too_big) else file_header(repo, path)
        role = classify_role(path, is_binary, header)

        lines = [] if too_big else hunks.get(path, [])
        if is_untracked and role != "binary":
            # Untracked files aren't in --numstat, so their size has to come from
            # the file itself. Oversized ones still get counted — just line-counted
            # rather than read into memory and regex-scanned — otherwise a large new
            # file is invisible to both the shape selector and aspect gating while
            # the note claims it was counted.
            try:
                if too_big:
                    with open(full, "rb") as fh:
                        added = sum(1 for _ in fh)
                else:
                    with open(full, "r", encoding="utf-8", errors="replace") as fh:
                        body = fh.readlines()
                    lines = ["+" + line for line in body]
                    added = len(body)
            except OSError:
                pass

        if too_big:
            notes.append(
                f"{path}: {size} bytes exceeds --max-file-bytes; "
                f"{added} lines counted, content not scanned for signals"
            )

        signals, evidence, file_notes = scan_signals(path, role, lines)
        notes.extend(file_notes)

        if role not in ("source", "wire_contract"):
            excluded[role] = excluded.get(role, 0) + added + removed

        st = "A" if is_untracked else status.get(path, "M")
        if st == "A" and role == "source":
            signals = sorted(set(signals) | {"new_module"})

        files.append({
            "path": path,
            "status": st,
            "role": role,
            "lang": LANG_BY_EXT.get(os.path.splitext(path)[1].lower()),
            "added": added,
            "removed": removed,
            "committed": path in committed_paths,
            "worktree": path in worktree_paths or is_untracked,
            "signals": signals,
            "evidence": evidence,
        })

    code = [f for f in files if f["role"] in ("source", "wire_contract")]
    code_lines = sum(f["added"] + f["removed"] for f in code)
    aspects = compute_aspects(files)
    shape = compute_shape(len(code), code_lines)

    if excluded.get("lockfile"):
        notes.append(
            f"lockfile churn excluded from code_lines ({excluded['lockfile']} lines) — "
            "dependency waves must not inflate the cost shape or activate logic review"
        )

    result = {
        "schema": SCHEMA,
        "base": base,
        "merge_base": merge_base,
        "head": head,
        "dirty": dirty,
        "totals": {
            "files": len(files),
            "insertions": sum(f["added"] for f in files),
            "deletions": sum(f["removed"] for f in files),
            "code_files": len(code),
            "code_lines": code_lines,
            "excluded": excluded,
        },
        "files": files,
        "aspects": aspects,
        "shape": shape,
        "notes": notes,
    }

    json.dump(result, sys.stdout, indent=2 if args.pretty else None)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
