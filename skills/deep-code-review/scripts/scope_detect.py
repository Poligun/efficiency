#!/usr/bin/env python3
"""Classify a branch diff so a review can gate on what actually changed.

Emits JSON on stdout: per-file role + signals, which review aspects are active,
and a cost shape. Read-only; runs git and nothing else.

The point of doing this in a script rather than by model judgment: the review
report claims "aspect X did not run", and that claim has to be reproducible.
It also keeps the orchestrator from reading the whole diff (and forming
opinions) before it has to arbitrate between agents that did.

Exit codes: 0 ok · 2 not a git repo · 3 no base resolvable · 4 empty range.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys

SCHEMA = 1

# --------------------------------------------------------------------------
# git plumbing
# --------------------------------------------------------------------------


def git(repo: str, *args: str, check: bool = True) -> str:
    proc = subprocess.run(
        ["git", "-C", repo, *args],
        capture_output=True,
        text=True,
    )
    if check and proc.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc.stdout


def resolve_base(repo: str, explicit: str | None) -> str | None:
    """Find the trunk this branch forked from.

    Deliberately NOT @{upstream}: on a pushed feature branch that resolves to
    the branch's own remote ref, and the diff collapses to whatever is
    uncommitted. We want "what this branch adds to the trunk", so trunk refs
    come first, and any candidate that is already an ancestor-equal of HEAD
    (i.e. we're standing on it) is skipped.
    """
    candidates = [explicit] if explicit else [
        "origin/HEAD", "origin/main", "origin/master", "main", "master", "@{upstream}"
    ]
    fallback = None
    for ref in candidates:
        if not ref:
            continue
        proc = subprocess.run(
            ["git", "-C", repo, "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"],
            capture_output=True, text=True,
        )
        if proc.returncode != 0:
            continue
        if explicit:
            return ref
        sha = proc.stdout.strip()
        head = git(repo, "rev-parse", "HEAD").strip()
        merge_base = git(repo, "merge-base", ref, "HEAD", check=False).strip()
        if sha == head or merge_base == head:
            # We're on the trunk (or behind it) — this ref yields nothing useful.
            fallback = fallback or ref
            continue
        return ref
    return fallback


