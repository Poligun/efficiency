LOCKFILES = {
    "Cargo.lock", "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "go.sum",
    "poetry.lock", "uv.lock", "Gemfile.lock", "composer.lock", "Pipfile.lock",
    "gradle.lockfile", "flake.lock", "bun.lockb",
}

MANIFESTS = {
    "Cargo.toml", "package.json", "go.mod", "pyproject.toml", "setup.py",
    "build.gradle", "build.gradle.kts", "pom.xml", "Gemfile", "Pipfile",
    "composer.json",
}

WIRE_EXTS = {".proto", ".graphql", ".gql", ".thrift", ".avsc", ".smithy", ".raml"}
DOC_EXTS = {".md", ".mdx", ".rst", ".txt", ".adoc"}
CONFIG_EXTS = {".yaml", ".yml", ".toml", ".json", ".ini", ".cfg", ".properties"}

CODE_EXTS = {
    ".rs", ".go", ".py", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".java",
    ".kt", ".kts", ".scala", ".swift", ".c", ".h", ".cc", ".cpp", ".hpp", ".hh",
    ".cs", ".rb", ".php", ".ex", ".exs", ".erl", ".hs", ".ml", ".dart", ".lua",
    ".sh", ".bash", ".zsh", ".sql", ".vue", ".svelte", ".m", ".mm", ".zig",
    ".clj", ".cljs", ".jl", ".nim", ".pl", ".r",
}

GENERATED_DIR_RE = re.compile(
    r"(^|/)(target|dist|build|node_modules|vendor|gen|\.generated|__pycache__)/"
)
GENERATED_NAME_RE = re.compile(
    r"(\.pb\.go|_pb2\.py|_pb2\.pyi|_pb\.js|\.g\.dart|\.generated\.[^.]+|\.min\.js|"
    r"\.min\.css|\.freezed\.dart)$"
)
GENERATED_HEADER_RE = re.compile(
    r"@generated|Code generated .* DO NOT EDIT|autogenerated|AUTO-GENERATED", re.I
)
TEST_PATH_RE = re.compile(r"(^|/)(tests?|__tests__|spec|specs|testdata|fixtures)/")
TEST_NAME_RE = re.compile(
    r"(^test_.*|.*_test\.[^.]+$|.*\.test\.[^.]+$|.*\.spec\.[^.]+$|.*Test\.java$|"
    r".*Tests\.cs$|conftest\.py$)"
)
OPENAPI_NAME_RE = re.compile(r"(openapi|swagger|api-spec)[^/]*\.(ya?ml|json)$", re.I)


def classify_role(path: str, is_binary: bool, header: str) -> str:
    base = os.path.basename(path)
    _, ext = os.path.splitext(base)
    ext = ext.lower()

    if base in LOCKFILES:
        return "lockfile"
    if base in MANIFESTS or re.match(r"requirements.*\.txt$", base) or ext == ".csproj":
        return "manifest"
    if GENERATED_DIR_RE.search(path) or GENERATED_NAME_RE.search(base):
        return "generated"
    if header and GENERATED_HEADER_RE.search(header):
        return "generated"
    if ext in WIRE_EXTS or OPENAPI_NAME_RE.search(base):
        return "wire_contract"
    if TEST_PATH_RE.search(path) or TEST_NAME_RE.match(base):
        return "test"
    if ext in DOC_EXTS:
        return "docs"
    if is_binary:
        return "binary"
    if ext in CODE_EXTS:
        return "source"
    if base == "Dockerfile" or ext in {".tf", ".tfvars"} or base.startswith(".env"):
        return "config"
    if ext in CONFIG_EXTS:
        return "config"
    return "unknown"


LANG_BY_EXT = {
    ".rs": "rust", ".go": "go", ".py": "python", ".ts": "ts", ".tsx": "ts",
    ".js": "js", ".jsx": "js", ".java": "java", ".kt": "kotlin", ".swift": "swift",
    ".cs": "csharp", ".rb": "ruby", ".c": "c", ".h": "c", ".cc": "cpp",
    ".cpp": "cpp", ".hpp": "cpp", ".proto": "proto", ".graphql": "graphql",
    ".sql": "sql", ".sh": "shell",
}


# --------------------------------------------------------------------------
# signals — regex over changed lines only, never whole files
# --------------------------------------------------------------------------

# Public/exported surface. Deliberately shallow: no parsing, no language server.
# Indentation guard (<= 4 columns) keeps nested helpers out.
API_SURFACE_RES = [
    re.compile(r"^\s{0,4}pub(\([^)]*\))?\s+(fn|struct|enum|trait|type|const|static|mod|use)\b"),
    re.compile(r"^\s{0,4}impl\b.*\bfor\b"),
    re.compile(r"^\s{0,4}(func|type|var|const)\s+\(?[A-Z]"),
    re.compile(r"^\s{0,4}export\s+(default\s+)?\w"),
    re.compile(r"^\s{0,4}declare\s+\w"),
    re.compile(r"^(def|class)\s+[A-Za-z]"),
    re.compile(r"^\s{0,4}__all__\s*="),
    re.compile(r"^\s{0,4}(public|open|internal|protected)\s+\w"),
    re.compile(r"^\s{0,4}(def self\.|module |class )\w"),
]
API_ALWAYS_PATHS = re.compile(r"(\.pyi$|\.d\.ts$|(^|/)(include|api|pkg|public)/)")

CLI_RE = re.compile(
    r"add_argument\(|#\[(arg|clap|command)|Command::new|\.option\(|yargs|"
    r"cobra\.Command|@click\.|argparse|flag\.(String|Bool|Int|Duration)"
)
ROUTE_RE = re.compile(
    r"@(Get|Post|Put|Patch|Delete)Mapping|app\.(get|post|put|patch|delete)\(|"
    r"router\.(get|post|put|patch|delete|route)\(|#\[(get|post|put|patch|delete|route)|"
    r"@app\.route|http\.HandleFunc|\.route\(|HttpServer::new"
)

# Wire-contract breakage. A removed field line, a reservation, a renumbering,
# or a removed rpc. `reserved` alone is not a defect (it's the correct removal
# ritual) — it's a marker that something WAS removed, which the reviewer needs.
PROTO_FIELD_RE = re.compile(r"^\s*(repeated\s+|optional\s+|required\s+)?[\w.<>, ]+\s+(\w+)\s*=\s*(\d+)\s*;")
RESERVED_RE = re.compile(r"^\s*reserved\s+")
RPC_RE = re.compile(r"^\s*rpc\s+(\w+)")
# NOTE: OpenAPI files are classified as wire_contract by name, but no breakage
# detection runs on their hunks — a naive "removed required-list entry" regex
# matches any YAML list item and would flood wire_breaking with false positives.
# Real OpenAPI diffing is tracked in meta/IMPROVEMENTS.md.

BUILD_CONTRACT_FILES = re.compile(
    r"(^|/)(build\.rs|build\.gradle(\.kts)?|CMakeLists\.txt|Makefile|"
    r"buf\.gen\.ya?ml|codegen\.ya?ml|gulpfile\.js|webpack\.config\.js)$"
)

SEMVER_RE = re.compile(r"(\d+)\.(\d+)\.?(\d+)?")
DEP_LINE_RE = re.compile(r'^[+-]\s*"?([\w@/._-]+)"?\s*[:=]\s*.*?"?[\^~>=<]*(\d+\.\d+(\.\d+)?)')


def dep_bumps(hunk_lines: list[str]) -> list[str]:
    """Major bumps (or 0.x minor bumps, which are majors in practice)."""
    removed: dict[str, str] = {}
    added: dict[str, str] = {}
    for line in hunk_lines:
        m = DEP_LINE_RE.match(line)
        if not m:
            continue
        name, ver = m.group(1), m.group(2)
        (removed if line.startswith("-") else added)[name] = ver
    out = []
    for name, new in added.items():
        old = removed.get(name)
        if not old or old == new:
            continue
        o, n = SEMVER_RE.match(old), SEMVER_RE.match(new)
        if not o or not n:
            continue
        o_major, o_minor = int(o.group(1)), int(o.group(2))
        n_major, n_minor = int(n.group(1)), int(n.group(2))
        if n_major != o_major or (n_major == 0 and n_minor != o_minor):
            out.append(f"{name} {old} -> {new}")
    return out


def scan_signals(path: str, role: str, hunk_lines: list[str]) -> tuple[list[str], list[str], list[str]]:
    """Return (signals, evidence lines, notes)."""
    signals: set[str] = set()
    evidence: list[str] = []
    notes: list[str] = []

    def note_evidence(line: str) -> None:
        if len(evidence) < 6:
            evidence.append(line.rstrip()[:160])

    if BUILD_CONTRACT_FILES.search(path):
        signals.add("build_contract_touched")

    if role == "manifest":
        bumps = dep_bumps(hunk_lines)
        if bumps:
            signals.add("dep_major_bump")
            notes.extend(bumps)

    # Names that survive the diff. A proto field that moves into a oneof, or an
    # rpc that gets re-indented, shows up as removed+added — that is not
    # breakage, and flagging it trains the reviewer to ignore the signal.
    surviving: set[str] = set()
    if role == "wire_contract":
        for raw in hunk_lines:
            if not raw.startswith("+"):
                continue
            m = PROTO_FIELD_RE.match(raw[1:]) or RPC_RE.match(raw[1:])
            if m:
                surviving.add(m.group(1) if m.re is RPC_RE else m.group(2))

    for raw in hunk_lines:
        body = raw[1:]
        added = raw.startswith("+")

        if role in ("source", "wire_contract"):
            if API_ALWAYS_PATHS.search(path):
                signals.add("api_surface_touched")
            for rx in API_SURFACE_RES:
                if rx.search(body):
                    signals.add("api_surface_touched")
                    if added:
                        note_evidence(raw)
                    break
            if CLI_RE.search(body):
                signals.add("cli_surface_touched")
            if ROUTE_RE.search(body):
                signals.add("http_route_touched")

        if role == "wire_contract" and not added:
            fm, rm = PROTO_FIELD_RE.match(body), RPC_RE.match(body)
            gone = (fm and fm.group(2) not in surviving) or (rm and rm.group(1) not in surviving)
            if RESERVED_RE.match(body) or gone:
                signals.add("wire_breaking")
                note_evidence(raw)

    # A retained field whose number changed is breakage that neither side shows
    # alone — compare the removed and added field maps.
    if role == "wire_contract":
        old_nums, new_nums = {}, {}
        for raw in hunk_lines:
            m = PROTO_FIELD_RE.match(raw[1:])
            if m:
                (new_nums if raw.startswith("+") else old_nums)[m.group(2)] = m.group(3)
        for name, num in new_nums.items():
            if name in old_nums and old_nums[name] != num:
                signals.add("wire_breaking")
                notes.append(f"{path}: field '{name}' renumbered {old_nums[name]} -> {num}")

    return sorted(signals), evidence, notes


# --------------------------------------------------------------------------
# diff parsing
# --------------------------------------------------------------------------


def parse_numstat(text: str) -> dict[str, tuple[int | None, int | None]]:
    out: dict[str, tuple[int | None, int | None]] = {}
    for line in text.splitlines():
        parts = line.split("\t")
        if len(parts) < 3:
            continue
        add, rem, path = parts[0], parts[1], parts[-1]
        binary = add == "-" or rem == "-"
        out[path] = (None, None) if binary else (int(add), int(rem))
    return out


def parse_name_status(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        out[parts[-1]] = parts[0][0]
    return out


def split_patch_by_file(patch: str) -> dict[str, list[str]]:
    """Map path -> changed lines (with leading +/-), ignoring hunk headers."""
    files: dict[str, list[str]] = {}
    current: str | None = None
    for line in patch.splitlines():
        if line.startswith("diff --git "):
            m = re.search(r" b/(.+)$", line)
            current = m.group(1) if m else None
            if current:
                files.setdefault(current, [])
        elif current and line.startswith(("+", "-")):
            if line.startswith(("+++", "---")):
                continue
            files[current].append(line)
    return files


def file_header(repo: str, path: str, limit: int = 30) -> str:
    full = os.path.join(repo, path)
    try:
        with open(full, "r", encoding="utf-8", errors="replace") as fh:
            return "".join(next(fh, "") for _ in range(limit))
    except OSError:
        return ""


