GIT_ENV = {**os.environ,
           "GIT_AUTHOR_NAME": "t", "GIT_AUTHOR_EMAIL": "t@t",
           "GIT_COMMITTER_NAME": "t", "GIT_COMMITTER_EMAIL": "t@t",
           "GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_SYSTEM": "/dev/null"}


def git(repo, *args):
    subprocess.run(["git", "-C", repo, *args], check=True,
                   capture_output=True, text=True, env=GIT_ENV)


def put(repo, rel, content):
    full = os.path.join(repo, rel)
    os.makedirs(os.path.dirname(full) or full, exist_ok=True) if os.path.dirname(rel) \
        else None
    with open(full, "w") as fh:
        fh.write(content)


def run_scope(repo, *args):
    proc = subprocess.run([sys.executable, SCRIPT, "--repo", repo, *args],
                          capture_output=True, text=True)
    data = json.loads(proc.stdout) if proc.returncode == 0 and proc.stdout else None
    return proc.returncode, data, proc.stderr


class IntegrationBase(unittest.TestCase):
    def setUp(self):
        self._tmp = tempfile.TemporaryDirectory()
        self.dir = self._tmp.name

    def tearDown(self):
        self._tmp.cleanup()

    def make_repo(self, name="repo", branch="main"):
        repo = os.path.join(self.dir, name)
        os.makedirs(repo)
        git(repo, "init", "-q", "-b", branch)
        return repo


