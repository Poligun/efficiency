def f(path, role="source", status="M", signals=(), added=10, removed=0):
    return {"path": path, "role": role, "status": status,
            "signals": sorted(signals), "added": added, "removed": removed}


class TestComputeAspects(unittest.TestCase):
    def test_all_inactive_on_dep_bump(self):
        files = [f("Cargo.toml", role="manifest", signals=["dep_major_bump"]),
                 f("Cargo.lock", role="lockfile", added=900)]
        a = sd.compute_aspects(files)
        for name in ("wire_api", "code_api", "logic", "convention"):
            self.assertFalse(a[name]["active"], name)

    def test_wire_active_via_contract_file(self):
        a = sd.compute_aspects([f("u.proto", role="wire_contract")])
        self.assertTrue(a["wire_api"]["active"])
        self.assertEqual(a["wire_api"]["strength"], "weak")  # modified, not breaking

    def test_wire_strong_on_breaking(self):
        a = sd.compute_aspects([f("u.proto", role="wire_contract",
                                  signals=["wire_breaking"])])
        self.assertEqual(a["wire_api"]["strength"], "strong")

    def test_wire_strong_on_new_contract(self):
        a = sd.compute_aspects([f("u.proto", role="wire_contract", status="A")])
        self.assertEqual(a["wire_api"]["strength"], "strong")

    def test_wire_active_via_routes_and_cli(self):
        a = sd.compute_aspects([f("s.py", signals=["http_route_touched"])])
        self.assertTrue(a["wire_api"]["active"])
        a = sd.compute_aspects([f("c.py", signals=["cli_surface_touched"])])
        self.assertTrue(a["wire_api"]["active"])

    def test_wire_active_via_build_contract_alone(self):
        # PR #1 bug 1: a pure build.rs change must activate wire_api.
        a = sd.compute_aspects([f("build.rs", signals=["build_contract_touched"])])
        self.assertTrue(a["wire_api"]["active"])
        self.assertIn("build.rs", a["wire_api"]["files"])

    def test_code_api_activation_and_strength(self):
        one = [f("a.rs", signals=["api_surface_touched"])]
        self.assertTrue(sd.compute_aspects(one)["code_api"]["active"])
        self.assertEqual(sd.compute_aspects(one)["code_api"]["strength"], "weak")

        three = [f(p, signals=["api_surface_touched"]) for p in ("a.rs", "b.rs", "c.rs")]
        self.assertEqual(sd.compute_aspects(three)["code_api"]["strength"], "strong")

        new = [f("a.rs", status="A", signals=["api_surface_touched", "new_module"])]
        self.assertEqual(sd.compute_aspects(new)["code_api"]["strength"], "strong")

    def test_generated_files_do_not_activate_code_api(self):
        a = sd.compute_aspects([f("x_pb2.py", role="generated",
                                  signals=["api_surface_touched"])])
        self.assertFalse(a["code_api"]["active"])

    def test_logic_threshold(self):
        self.assertFalse(sd.compute_aspects([f("a.rs", added=24)])["logic"]["active"])
        on = sd.compute_aspects([f("a.rs", added=25)])["logic"]
        self.assertTrue(on["active"])
        self.assertEqual(on["strength"], "weak")
        self.assertEqual(sd.compute_aspects([f("a.rs", added=150)])["logic"]["strength"],
                         "strong")

    def test_logic_counts_only_code_roles(self):
        files = [f("Cargo.lock", role="lockfile", added=5000),
                 f("README.md", role="docs", added=500),
                 f("a.rs", added=10)]
        self.assertFalse(sd.compute_aspects(files)["logic"]["active"])

    def test_logic_removed_lines_count(self):
        a = sd.compute_aspects([f("a.rs", added=0, removed=30)])
        self.assertTrue(a["logic"]["active"])

    def test_convention_only_on_new_code(self):
        self.assertFalse(sd.compute_aspects([f("a.rs")])["convention"]["active"])
        a = sd.compute_aspects([f("src/new.rs", status="A", signals=["new_module"])])
        self.assertTrue(a["convention"]["active"])

    def test_convention_strong_only_for_whole_new_dir(self):
        # New file in a directory that also has modified files → weak.
        mixed = [f("src/new.rs", status="A", signals=["new_module"]), f("src/old.rs")]
        self.assertEqual(sd.compute_aspects(mixed)["convention"]["strength"], "weak")
        # New file whose directory contains nothing pre-existing → strong.
        fresh = [f("src/alerts/mod.rs", status="A", signals=["new_module"]),
                 f("src/old.rs")]
        self.assertEqual(sd.compute_aspects(fresh)["convention"]["strength"], "strong")


