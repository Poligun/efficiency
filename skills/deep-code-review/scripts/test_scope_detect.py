class TestScanSignals(unittest.TestCase):
    def signals(self, path, role, lines):
        sig, _ev, notes = sd.scan_signals(path, role, lines)
        return sig, notes

    def test_api_surface_across_languages(self):
        for line in [
            "+pub fn connect() -> Client {",       # rust
            "+pub(crate) struct Config {",         # rust scoped
            "+func NewServer(cfg Config) *Server", # go exported
            "+export default class Widget {",      # ts/js
            "+def handle(request):",               # python top-level
            "+class Parser:",                      # python class
            "+__all__ = ['x']",                    # python export list
            "+public String getName() {",          # java
        ]:
            sig, _ = self.signals("src/lib.rs", "source", [line])
            self.assertIn("api_surface_touched", sig, f"missed: {line!r}")

    def test_removed_surface_still_signals(self):
        # A deleted export is an API change too; only *evidence* is added-only.
        sig, _ = self.signals("src/lib.rs", "source", ["-pub fn gone() {}"])
        self.assertIn("api_surface_touched", sig)

    def test_nested_helper_does_not_signal(self):
        sig, _ = self.signals("src/lib.rs", "source", ["+        pub fn inner() {}"])
        self.assertNotIn("api_surface_touched", sig)

    def test_api_always_paths(self):
        for path in ["types/foo.d.ts", "stubs/mod.pyi", "include/header.h", "pkg/client.go"]:
            sig, _ = self.signals(path, "source", ["+x = 1"])
            self.assertIn("api_surface_touched", sig, path)

    def test_cli_and_route_surface(self):
        sig, _ = self.signals("src/cli.py", "source", ['+parser.add_argument("--force")'])
        self.assertIn("cli_surface_touched", sig)
        sig, _ = self.signals("src/http.ts", "source", ['+app.get("/users", listUsers)'])
        self.assertIn("http_route_touched", sig)
        sig, _ = self.signals("src/main.go", "source", ['+http.HandleFunc("/health", ok)'])
        self.assertIn("http_route_touched", sig)

    def test_signals_gated_to_code_roles(self):
        sig, _ = self.signals("README.md", "docs", ["+pub fn x() {}"])
        self.assertEqual(sig, [])

    def test_wire_breaking_on_removed_field(self):
        sig, _ = self.signals("a.proto", "wire_contract", ["-  string email = 4;"])
        self.assertIn("wire_breaking", sig)

    def test_wire_breaking_on_reserved(self):
        sig, _ = self.signals("a.proto", "wire_contract", ["-reserved 7;"])
        # `reserved` on a removed line marks that a removal happened.
        self.assertIn("wire_breaking", sig)

    def test_moved_field_is_not_breaking(self):
        # Field relocated (e.g. into a oneof): removed+added with same name.
        sig, _ = self.signals("a.proto", "wire_contract",
                              ["-  string email = 4;", "+    string email = 4;"])
        self.assertNotIn("wire_breaking", sig)

    def test_moved_rpc_is_not_breaking(self):
        sig, _ = self.signals("a.proto", "wire_contract",
                              ["-  rpc GetUser(Req) returns (Resp);",
                               "+    rpc GetUser(Req) returns (Resp);"])
        self.assertNotIn("wire_breaking", sig)

    def test_removed_rpc_is_breaking(self):
        sig, _ = self.signals("a.proto", "wire_contract",
                              ["-  rpc DeleteUser(Req) returns (Resp);"])
        self.assertIn("wire_breaking", sig)

    def test_renumbered_field_is_breaking_with_note(self):
        sig, notes = self.signals("a.proto", "wire_contract",
                                  ["-  string email = 4;", "+  string email = 5;"])
        self.assertIn("wire_breaking", sig)
        self.assertTrue(any("renumbered 4 -> 5" in n for n in notes), notes)

    def test_build_contract_touched(self):
        for path in ["build.rs", "svc/buf.gen.yaml", "app/build.gradle.kts", "Makefile"]:
            sig, _ = self.signals(path, "source", [])
            self.assertIn("build_contract_touched", sig, path)

    def test_manifest_bump_lands_in_notes(self):
        _, notes = self.signals("Cargo.toml", "manifest",
                                ['-x = "1.0.0"', '+x = "2.0.0"'])
        self.assertEqual(notes, ["x 1.0.0 -> 2.0.0"])


