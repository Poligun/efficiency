class TestBranchReview(IntegrationBase):
    """One feature branch exercising committed+worktree+untracked at once."""

    def build(self):
        repo = self.make_repo()
        put(repo, "src/lib.rs", "fn private() {}\n")
        put(repo, "Cargo.toml", '[dependencies]\nserde = "1.0.0"\n')
        put(repo, "Cargo.lock", "# lock\n" + "line\n" * 50)
        git(repo, "add", "."); git(repo, "commit", "-qm", "init")
        git(repo, "checkout", "-qb", "feat")
        # committed: exported surface + dep major bump + lockfile churn
        put(repo, "src/lib.rs", "fn private() {}\npub fn api() {}\n")
        put(repo, "Cargo.toml", '[dependencies]\nserde = "2.0.0"\n')
        put(repo, "Cargo.lock", "# lock\n" + "other\n" * 300)
        put(repo, "src/alerts/mod.rs", "pub fn alert() {}\n")
        git(repo, "add", "."); git(repo, "commit", "-qm", "feature")
        # worktree edit on an already-committed file
        put(repo, "src/lib.rs", "fn private() {}\npub fn api() {}\n// wip\n")
        # untracked new file
        put(repo, "src/extra.rs", "pub fn extra() {}\n")
        return repo

    def test_full_classification(self):
        repo = self.build()
        code, data, err = run_scope(repo)
        self.assertEqual(code, 0, err)
        by_path = {x["path"]: x for x in data["files"]}

        lib = by_path["src/lib.rs"]
        self.assertTrue(lib["committed"] and lib["worktree"],
                        "a file changed in a commit AND the worktree is both")
        self.assertIn("api_surface_touched", lib["signals"])

        extra = by_path["src/extra.rs"]
        self.assertEqual(extra["status"], "A")
        self.assertFalse(extra["committed"])
        self.assertTrue(extra["worktree"])
        self.assertIn("new_module", extra["signals"])
        self.assertGreater(extra["added"], 0, "untracked files must be line-counted")

        self.assertEqual(by_path["Cargo.lock"]["role"], "lockfile")
        self.assertIn("dep_major_bump", by_path["Cargo.toml"]["signals"])
        self.assertTrue(any("serde 1.0.0 -> 2.0.0" in n for n in data["notes"]))

        self.assertTrue(data["dirty"])
        # lockfile churn excluded from code_lines
        self.assertLess(data["totals"]["code_lines"], 50)
        self.assertGreaterEqual(data["totals"]["excluded"].get("lockfile", 0), 300)
        self.assertTrue(any("lockfile churn excluded" in n for n in data["notes"]))

        self.assertTrue(data["aspects"]["code_api"]["active"])
        self.assertTrue(data["aspects"]["convention"]["active"])
        self.assertEqual(data["aspects"]["convention"]["strength"], "strong",
                         "src/alerts/ is a whole new directory")
        self.assertFalse(data["aspects"]["wire_api"]["active"])

    def test_no_untracked_flag(self):
        repo = self.build()
        code, data, err = run_scope(repo, "--no-untracked")
        self.assertEqual(code, 0, err)
        self.assertNotIn("src/extra.rs", {x["path"] for x in data["files"]})


class TestOversizedUntracked(IntegrationBase):
    def test_counted_not_scanned(self):
        # PR #1 bug 2: oversized untracked files must still be line-counted.
        repo = self.make_repo()
        put(repo, "a.txt", "x\n")
