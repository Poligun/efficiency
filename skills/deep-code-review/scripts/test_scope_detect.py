class TestDepBumps(unittest.TestCase):
    def bumps(self, lines):
        return sd.dep_bumps(lines)

    def test_major_bump_toml(self):
        out = self.bumps(['-alpha = "1.2.3"', '+alpha = "2.0.0"'])
        self.assertEqual(out, ["alpha 1.2.3 -> 2.0.0"])

    def test_zero_x_minor_is_major(self):
        out = self.bumps(['-beta = "0.12.4"', '+beta = "0.13.0"'])
        self.assertEqual(out, ["beta 0.12.4 -> 0.13.0"])

    def test_minor_and_patch_are_not_bumps(self):
        self.assertEqual(self.bumps(['-a = "1.2.0"', '+a = "1.3.0"']), [])
        self.assertEqual(self.bumps(['-a = "1.2.0"', '+a = "1.2.9"']), [])

    def test_zero_x_patch_is_not_a_bump(self):
        self.assertEqual(self.bumps(['-a = "0.12.4"', '+a = "0.12.9"']), [])

    def test_package_json_style(self):
        out = self.bumps(['-  "left-pad": "^1.3.0",', '+  "left-pad": "^2.0.1",'])
        self.assertEqual(out, ["left-pad 1.3.0 -> 2.0.1"])

    def test_added_without_removed_is_not_a_bump(self):
        self.assertEqual(self.bumps(['+newdep = "3.0.0"']), [])

    def test_unparseable_lines_ignored(self):
        self.assertEqual(self.bumps(["-[dependencies]", "+[dependencies]"]), [])


